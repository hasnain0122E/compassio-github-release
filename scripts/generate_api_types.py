"""Generate TypeScript types from the FastAPI OpenAPI schema (no third-party generator).

    uv run python scripts/generate_api_types.py            # writes both files below
    uv run python scripts/generate_api_types.py --check    # exit 1 if either file is stale

Writes apps/web/src/lib/api-types.ts and the OpenAPI document docs/api/openapi.json (the
frontend handoff contract, Task 009).

The output is GENERATED; never edit it by hand. tests/api/test_api_types.py enforces freshness.
"""

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any

REPO = Path(__file__).resolve().parents[1]
OUTPUT = REPO / "apps" / "web" / "src" / "lib" / "api-types.ts"
OPENAPI_OUTPUT = REPO / "docs" / "api" / "openapi.json"
HEADER = (
    "// GENERATED by scripts/generate_api_types.py from the Compassio API OpenAPI schema.\n"
    "// Do not edit by hand: run `uv run python scripts/generate_api_types.py`.\n"
)


def _name(raw: str) -> str:
    """OpenAPI component name -> TypeScript identifier (e.g. 'Budget-Input' -> 'Budget_Input')."""
    return re.sub(r"[^A-Za-z0-9_$]", "_", raw)


def _ts(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        return _name(str(schema["$ref"]).rsplit("/", 1)[-1])
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(v) for v in schema["enum"])
    for key in ("anyOf", "oneOf"):
        if key in schema:
            parts = []
            for item in schema[key]:
                text = _ts(item)
                if text not in parts:
                    parts.append(text)
            return " | ".join(parts)
    kind = schema.get("type")
    if kind == "string":
        return "string"
    if kind in ("integer", "number"):
        return "number"
    if kind == "boolean":
        return "boolean"
    if kind == "null":
        return "null"
    if kind == "array":
        inner = _ts(schema.get("items", {}))
        return f"Array<{inner}>"
    if kind == "object":
        if schema.get("properties"):
            return _object(schema)
        extra = schema.get("additionalProperties")
        value = _ts(extra) if isinstance(extra, dict) and extra else "unknown"
        return f"Record<string, {value}>"
    return "unknown"


def _object(schema: dict[str, Any], indent: str = "  ") -> str:
    required = set(schema.get("required", []))
    lines = ["{"]
    for name, prop in schema.get("properties", {}).items():
        optional = "" if name in required else "?"
        lines.append(f"{indent}{json.dumps(name)}{optional}: {_ts(prop)};")
    lines.append("}")
    return "\n".join(lines)


def render(openapi: dict[str, Any]) -> str:
    out = [HEADER]
    for name, schema in sorted(openapi.get("components", {}).get("schemas", {}).items()):
        if schema.get("type") == "object" or "properties" in schema:
            out.append(f"export interface {_name(name)} {_object(schema)}\n")
        else:
            out.append(f"export type {_name(name)} = {_ts(schema)};\n")
    return "\n".join(out)


def render_openapi(openapi: dict[str, Any]) -> str:
    return json.dumps(openapi, indent=1, sort_keys=True, ensure_ascii=False) + "\n"


def current_schema() -> dict[str, Any]:
    from compassio_api.core.config import Settings
    from compassio_api.main import create_app

    schema: dict[str, Any] = create_app(Settings(_env_file=None)).openapi()
    return schema


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    schema = current_schema()
    outputs = {OUTPUT: render(schema), OPENAPI_OUTPUT: render_openapi(schema)}
    if args.check:
        stale = [
            path
            for path, text in outputs.items()
            if not path.is_file() or path.read_text(encoding="utf-8") != text
        ]
        names = ", ".join(str(p.relative_to(REPO)) for p in stale)
        print(f"stale: {names}" if stale else "up to date")
        return 1 if stale else 0
    for path, text in outputs.items():
        path.write_text(text, encoding="utf-8", newline="\n")
        print(f"Wrote {path.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
