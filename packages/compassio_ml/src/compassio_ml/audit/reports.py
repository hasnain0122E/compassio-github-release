"""Deterministic machine-readable audit artifacts.

Every file except ``run_metadata.json`` is byte-identical across runs on the same
inputs, so reproducibility can be checked by hashing the output directory.
"""

import csv
import json
import platform
from collections.abc import Iterable, Sequence
from dataclasses import dataclass
from datetime import UTC, datetime
from importlib.metadata import version
from pathlib import Path

from pydantic import BaseModel

from compassio_ml.audit.inspectors import INSPECTORS, SourceAudit
from compassio_ml.audit.loaders import SourceData
from compassio_ml.audit.models import (
    CoverageRow,
    FinancialField,
    LabelRow,
    OverlapRow,
    PakistanRow,
    QualityIssue,
    TableSchema,
    Year2026Row,
)
from compassio_ml.audit.overlap import OverlapResult, investigate_overlap
from compassio_ml.audit.research_audit import ResearchLabelAudit, audit_research_labels
from compassio_ml.data.inventory import Inventory, build_inventory
from compassio_ml.data.layout import DataLayout, MissingSourceDataError

DEFAULT_ARTIFACT_DIR = Path("artifacts") / "data_audit"
DETERMINISTIC_FILES = (
    "source_inventory.json",
    "coverage_summary.csv",
    "research_label_distribution.csv",
    "pakistan_coverage.csv",
    "year_2026_coverage.csv",
    "financial_fields.csv",
    "data_quality_issues.csv",
    "source_overlap_review.csv",
    "source_schemas.json",
    "source_schemas.md",
    "audit_facts.json",
)


def _write_csv[M: BaseModel](path: Path, rows: Sequence[M], model: type[M]) -> None:
    columns = list(model.model_fields)
    with path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.writer(handle, lineterminator="\n")
        writer.writerow(columns)
        for row in rows:
            data = row.model_dump(mode="json")
            writer.writerow(["" if data[c] is None else data[c] for c in columns])


def _write_json(path: Path, payload: object) -> None:
    path.write_text(
        json.dumps(payload, indent=2, sort_keys=True, ensure_ascii=False, default=str) + "\n",
        encoding="utf-8",
    )


def render_schema_markdown(schemas: Sequence[TableSchema]) -> str:
    """Column-by-column profile of every inspected table (generated; do not hand-edit)."""
    lines = [
        "<!-- Generated by `uv run compassio-data audit`; do not edit by hand. -->",
        "",
    ]
    for table in schemas:
        lines += [
            f"### `{table.source_id}` / {table.table}",
            "",
            f"Unit of observation: {table.unit_of_observation}. Rows: {table.row_count:,}.",
            "",
            "| Column | Non-blank | Blank | Distinct |",
            "| --- | ---: | ---: | ---: |",
        ]
        for col in table.columns:
            name = col.name.replace("|", "\\|")
            lines.append(f"| `{name}` | {col.non_blank:,} | {col.blank:,} | {col.distinct:,} |")
        lines.append("")
    return "\n".join(lines)


def inventory_payload(inventory: Inventory, data_root_label: str) -> dict[str, object]:
    """Inventory without the run timestamp (that goes to run_metadata.json)."""
    payload = inventory.model_dump(mode="json", exclude={"inspected_at", "data_root"})
    payload["data_root"] = data_root_label
    payload["distinct_file_count"] = inventory.distinct_file_count
    return payload


def write_inventory(inventory: Inventory, out_dir: Path, data_root_label: str) -> Path:
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / "source_inventory.json"
    _write_json(path, inventory_payload(inventory, data_root_label))
    return path


@dataclass
class AuditRun:
    inventory: Inventory
    sources: list[SourceAudit]
    labels: ResearchLabelAudit
    overlap: OverlapResult


def run_audit(layout: DataLayout) -> AuditRun:
    inventory = build_inventory(layout)
    if inventory.missing_critical_sources:
        raise MissingSourceDataError(
            "Critical sources missing or invalid: "
            + ", ".join(inventory.missing_critical_sources)
            + ". Place the original files in data/raw/<source_id>/ and re-run."
        )
    data = SourceData(layout)
    present = {r.source_id for r in inventory.records if r.error is None}
    sources = [inspect(data) for sid, inspect in INSPECTORS.items() if sid in present]
    return AuditRun(
        inventory=inventory,
        sources=sources,
        labels=audit_research_labels(data),
        overlap=investigate_overlap(data, inventory),
    )


def _flatten[T](groups: Iterable[list[T]]) -> list[T]:
    return [item for group in groups for item in group]


def write_audit(run: AuditRun, out_dir: Path, data_root_label: str) -> list[Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    write_inventory(run.inventory, out_dir, data_root_label)
    s = run.sources
    _write_csv(out_dir / "coverage_summary.csv", _flatten(a.coverage for a in s), CoverageRow)
    _write_csv(out_dir / "research_label_distribution.csv", run.labels.distribution, LabelRow)
    _write_csv(out_dir / "pakistan_coverage.csv", _flatten(a.pakistan for a in s), PakistanRow)
    _write_csv(out_dir / "year_2026_coverage.csv", _flatten(a.year2026 for a in s), Year2026Row)
    _write_csv(out_dir / "financial_fields.csv", _flatten(a.financial for a in s), FinancialField)
    issues = sorted(
        _flatten(a.issues for a in s),
        key=lambda i: (
            ["critical", "warning", "info"].index(i.severity.value),
            i.source_id,
            i.issue_id,
        ),
    )
    _write_csv(out_dir / "data_quality_issues.csv", issues, QualityIssue)
    _write_csv(out_dir / "source_overlap_review.csv", run.overlap.rows, OverlapRow)
    _write_json(
        out_dir / "source_schemas.json",
        [t.model_dump(mode="json") for a in s for t in a.schemas],
    )
    (out_dir / "source_schemas.md").write_text(
        render_schema_markdown([t for a in s for t in a.schemas]), encoding="utf-8"
    )
    _write_json(
        out_dir / "audit_facts.json",
        {
            "sources": {
                a.source_id: {"primary_record_count": a.primary_record_count, **a.facts} for a in s
            },
            "research_labels": run.labels.facts,
            "overlap": run.overlap.facts,
        },
    )
    _write_json(
        out_dir / "run_metadata.json",
        {
            "generated_at": datetime.now(UTC).isoformat(),
            "inventory_inspected_at": run.inventory.inspected_at.isoformat(),
            "python": platform.python_version(),
            "platform": platform.platform(),
            "packages": {
                p: version(p) for p in ("compassio-ml", "pandas", "openpyxl", "defusedxml")
            },
            "deterministic_files": list(DETERMINISTIC_FILES),
        },
    )
    return [out_dir / name for name in (*DETERMINISTIC_FILES, "run_metadata.json")]
